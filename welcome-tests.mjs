import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {shouldSkipWelcome,catalogEnteredURL} from './welcome-routing.js';
const base='https://polandent223.github.io/catalogo-poladent/';
assert.equal(shouldSkipWelcome(base),false);
assert.equal(shouldSkipWelcome(base+'?marca=ADALTA'),true);
assert.equal(shouldSkipWelcome(base+'?marca=IMODONTO#producto=abc'),true);
assert.equal(shouldSkipWelcome(base+'#producto=abc'),true);
assert.equal(shouldSkipWelcome(base+'?catalogo=1'),true);
assert.equal(shouldSkipWelcome(base+'#catalogo'),true);
assert.equal(shouldSkipWelcome(base+'?x=1'),false);
assert.equal(catalogEnteredURL(base),base+'?catalogo=1');
const html=readFileSync('index.html','utf8');
assert.ok(html.includes('id="welcome-screen"'));
assert.ok(html.includes('id="welcome-image"'));
assert.ok(html.includes('id="welcome-enter"'));
assert.ok(!html.includes('id="welcome-enter-mobile"'), 'No debe haber un segundo botón duplicado en móviles');
assert.ok(html.includes('id="catalog-app" hidden'));
assert.ok(html.includes('src="welcome.js"'));
assert.ok(html.includes('id="brand-shortcuts"'));
assert.ok(html.includes('id="detail"'));
assert.ok(!html.includes('src="public-catalog.js"'), 'El catálogo no debe precargarse mientras la portada está visible');
const welcome=readFileSync('welcome.js','utf8');
assert.ok(welcome.includes("import('./public-catalog.js')"));
assert.ok(welcome.includes("getElement")===false);
assert.ok(welcome.includes("catalogPublic/_catalog_contacts"));
assert.ok(welcome.includes("data.welcome_enabled?.booleanValue!==true"));
assert.ok(welcome.includes("data.welcome_image_url?.stringValue"));
assert.ok(welcome.includes("if(shouldSkipWelcome(location.href))enterCatalog()"));
assert.ok(welcome.includes("$('#welcome-enter').addEventListener('click'"));
assert.ok(welcome.includes("backdrop.style.setProperty('--welcome-backdrop'"));
const admin=readFileSync('admin.html','utf8');
assert.ok(admin.includes('href="portada.html"'));
const firebase=readFileSync('firebase-client.js','utf8');
assert.ok(firebase.includes('await adminCheck();\n  const url=String(settings.image_url'));
assert.ok(firebase.includes("doc(db,'catalogPublic',CONTACTS_DOC)"));
assert.ok(firebase.includes("doc(db,'catalogProducts',CONTACTS_DOC)"));
assert.ok(firebase.includes("batch.set(doc(db,'catalogProducts',CONTACTS_DOC),data,{merge:true})"));
assert.ok(firebase.includes("batch.set(doc(db,'catalogPublic',CONTACTS_DOC),data,{merge:true})"));
assert.ok(firebase.includes("batch.set(doc(db, 'catalogProducts', CONTACTS_DOC), data, {merge:true})"));
assert.ok(firebase.includes("batch.set(doc(db, 'catalogPublic', CONTACTS_DOC), data, {merge:true})"));
assert.ok(firebase.includes("welcome_image_url:url"));
assert.ok(firebase.includes("welcome_enabled:settings.enabled===true"));
assert.ok(firebase.includes("contacts: cleaned"));

const welcomeData=firebase.slice(firebase.indexOf('export async function saveWelcomeSettings('),firebase.indexOf('// Agenda de WhatsApp'));
assert.ok(welcomeData.includes("status:'available'"),'La portada debe tener estado permitido por Firestore');
const rules=readFileSync('firestore.rules','utf8');
assert.ok(rules.includes("request.resource.data.status in ['available', 'sold_out']"));

const welcomePanel=readFileSync('welcome-admin.js','utf8');
assert.ok(welcomePanel.includes("step==='firestore'"));
assert.ok(welcomePanel.includes("pendingUpload=uploaded"));
assert.ok(welcomePanel.includes("La fotografía ya está subida"));
const publicJS=readFileSync('catalog-public-data.js','utf8');
assert.ok(publicJS.includes("if (data.kind || !allowedStatuses.has(data.status)"));
const styles=readFileSync('catalog-style.css','utf8');
assert.ok(styles.includes('#welcome-screen[hidden],#welcome-loading[hidden],#catalog-app[hidden]{display:none!important}'), 'Pantallas ocultas no deben ocupar espacio');
assert.ok(styles.includes('width:min(99vw,133.3svh,1920px)'), 'La portada debe aprovechar el área visual en PC');
assert.ok(styles.includes('background:var(--welcome-backdrop'), 'Fondo extendido a partir de la portada oficial');
assert.ok(styles.includes('.welcome-hotspot{display:block'), 'El CTA visible en la imagen debe ser interactivo en móviles');
assert.ok(styles.includes('min-height:44px'), 'La zona de pulsación táctil debe ser cómoda');
assert.ok(!html.includes('class="welcome-mobile-copy"'), 'No repetir textos que ya existen en la portada oficial');
assert.ok(!html.includes('id="welcome-enter-mobile"'), 'No repetir botón de entrada en móviles');
console.log('Portada oficial: rutas, botón, activación y protección del administrador verificadas.');
