import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source = readFileSync(new URL('./bulk-import.js', import.meta.url), 'utf8');
const { parseCSV, readEntries } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const header='codigo,nombre,marca,descripcion,estado,foto,imagen_url,orden\n';
const entry='1,Forceps,MEDESY,Instrumento,disponible,forceps.jpg,,1\n';
assert.equal(readEntries(header+entry).length,1);
assert.equal(readEntries(header+entry)[0].source_key,'csv-medesy-1');
assert.equal(readEntries(header+entry)[0].status,'available');
assert.equal(readEntries(header+'1,Forceps,MEDESY,,agotado,forceps.jpg,,1\n')[0].status,'sold_out');
assert.equal(readEntries(header+'1,Forceps,MEDESY,,oculto,forceps.jpg,,1\n')[0].status,'hidden');
assert.equal(readEntries(header+'1,Forceps,MEDESY,,,,https://example.com/photo.jpg,1\n')[0].image_url,'https://example.com/photo.jpg');
assert.deepEqual(parseCSV('nombre;marca;foto\n"Elevador, recto";ICE;foto.jpg'),[['nombre','marca','foto'],['Elevador, recto','ICE','foto.jpg']]);
assert.equal(readEntries('nombre;marca;foto\n"Elevador, recto";ICE;foto.jpg')[0].name,'Elevador, recto');
assert.equal(readEntries('nombre,marca,foto\n"nombre con ""comillas""",ICE,foto.jpg')[0].name,'nombre con "comillas"');
assert.throws(()=>readEntries('nombre,marca,foto\nForceps,MEDESY,f.jpg\nForceps,MEDESY,g.jpg'),/repetidos/);
assert.throws(()=>readEntries(header+'1,Forceps,MEDESY,,,,http://example.com/a.jpg,1\n'),/https/);
assert.throws(()=>readEntries('nombre,marca,foto\n"sin cerrar,ICE,a.jpg'),/comillas/);
assert.throws(()=>readEntries('nombre,marca,foto\nMEDESY,,f.jpg'),/vacíos/);
assert.throws(()=>readEntries('nombre,marca,foto\nForceps,MEDESY,'),/foto o imagen_url/);
assert.throws(()=>readEntries('nombre,marca,foto\n'+Array.from({length:201},(_,i)=>'Producto '+i+',ICE,'+i+'.jpg').join('\n')),/200/);
const denco='codigo,nombre,marca,descripcion,estado,foto,imagen_url,orden,area_id\n'+
  'DENCO-001,PRIMARY FILE,DENCO,Limas de aleación azul,oculto,primary.webp,,1,endodoncia\n';
const den=readEntries(denco);
assert.equal(den.length,1);
assert.equal(den[0].area_id,'endodoncia');
assert.equal(den[0].status,'hidden');
assert.equal(den[0].source_key,'csv-denco-denco-001');
assert.equal(readEntries(header+'2,Forceps,MEDESY,,disponible,forceps.webp,,2\n')[0].area_id,'');
assert.throws(()=>readEntries(denco.replace('endodoncia','mal area')),/area_id/);

assert.equal(readEntries('nombre,marca,foto,area\nLimas,DENCO,limas.webp,endodoncia')[0].area_id,'endodoncia');
assert.equal(readEntries('nombre,marca,foto,categoria\nMotor endodóntico,DENCO,motor.webp,endodoncia')[0].area_id,'endodoncia');
const template = readFileSync(new URL('./plantilla_productos.csv', import.meta.url),'utf8');
assert.equal(template.trim().split(',').at(-1),'area_id');
assert.equal(readEntries(template+'1,Prueba,DENCO,,oculto,prueba.webp,,1,endodoncia\n')[0].status,'hidden');
console.log('Importador CSV: pruebas de área, plantilla y compatibilidad correctas.');
