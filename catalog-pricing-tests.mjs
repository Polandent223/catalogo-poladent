import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=name=>readFileSync(new URL('./'+name,import.meta.url),'utf8');
const load=async name=>import('data:text/javascript;base64,'+Buffer.from(read(name)).toString('base64'));
const {cleanUSD,convertVES,formatUSD,formatVES,validateBcvRate,fetchBcvRate}=await load('catalog-pricing.js');
const today=new Date('2026-10-27T14:00:00Z');
assert.equal(cleanUSD('10.50'),10.5);
assert.equal(cleanUSD(''),null);
assert.equal(cleanUSD(null),null);
assert.throws(()=>cleanUSD(0));
assert.throws(()=>cleanUSD(-2));
assert.throws(()=>cleanUSD(1.234));
assert.throws(()=>cleanUSD('una cosa'));
assert.equal(convertVES(10,887.302),8873.02);
assert.equal(convertVES(5.50,887.302),4880.16);
assert.equal(convertVES(null,887.302),null);
assert.equal(convertVES(5,0),null);
assert.match(formatUSD(10),/10,00/);
assert.match(formatVES(8873.02),/8.873,02/);
const bcv=validateBcvRate({USD:887.302,effective_date:'2026-10-27'},today);
assert.equal(bcv.usd_ves,887.302);
assert.equal(bcv.effective_date,'2026-10-27');
assert.match(bcv.provider,/independiente/);
assert.throws(()=>validateBcvRate({USD:0,effective_date:'2026-10-27'},today));
assert.throws(()=>validateBcvRate({USD:887,effective_date:'2026-10-18'},today));
assert.throws(()=>validateBcvRate({USD:887,effective_date:'2026-10-29'},today));
assert.throws(()=>validateBcvRate({USD:887,effective_date:'invalido'},today));
assert.equal((await fetchBcvRate(async()=>({ok:true,json:async()=>({USD:887.302,effective_date:'2026-10-27'})}),today)).usd_ves,887.302);
await assert.rejects(()=>fetchBcvRate(async()=>({ok:false}),today));
const publicParser=read('catalog-public-data.js');
assert.ok(publicParser.includes("pricingEnabled=data.pricing?.enabled===true"));
assert.ok(publicParser.includes('pricingEnabled=false'));
const page=read('index.html'),catalog=read('public-catalog.js');
assert.ok(page.includes('id="detail-price"'));
assert.ok(page.includes('id="bcv-rate-banner"'));
assert.ok(catalog.includes('if(!pricingEnabled||'), 'Nunca presentar precios cuando no estén activados.');
assert.ok(catalog.includes('if(pricingEnabled){'), 'Consultar la tasa solo al publicar precios.');
assert.ok(catalog.includes('setInterval(refreshBcvRate,30*60*1000)'), 'Actualizar la tasa periódicamente.');
assert.ok(catalog.includes("if(bcvRate){"), 'No inventar conversiones sin tasa válida.');
const backend=read('firebase-client.js');
assert.ok(backend.includes("price_usd: cleanUSD(body.price_usd)"));
assert.ok(backend.includes("if(!pricing.enabled)delete publicProduct.price_usd"), 'No publicar USD antes de activar.');
assert.ok(backend.includes("if(!pricingEnabled)delete publicProduct.price_usd"), 'No publicar precios importados antes de activar.');
assert.ok(backend.includes('await saveFlag()'), 'Sincronizar bandera de publicación al confirmar.');
assert.ok(backend.includes('if(active)await saveFlag()'), 'Publicar solo después de preparar las fichas.');
assert.ok(backend.includes('if(!active)await saveFlag()'), 'Desactivar visibilidad antes de retirar fichas.');
assert.ok(!read('firestore.rules').includes('catalogPrices'), 'Sin cambios en reglas de Firebase.');
const admin=read('admin.html');
assert.ok(admin.includes('id="price-usd"'));
assert.ok(admin.includes('href="precios.html"'));
assert.ok(read('admin.js').includes("price_usd:$('#price-usd').value.trim()||null"));
assert.ok(read('precios.html').includes('id="pricing-switch"'));
assert.ok(read('pricing-admin.js').includes('confirm(question)'));
console.log('POLADENT: USD + Bs BCV, controles privados, validación y bandera segura correctos.');
