import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('./contact-links.js', import.meta.url),'utf8');
const {whatsappInquiryURL}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const product={name:'Horno Lótus',brand:'VRC',status:'available'};
const link='https://polandent223.github.io/catalogo-poladent/?marca=VRC#producto=ABC123';
const url=whatsappInquiryURL('584121234567',product,link);
assert.ok(url.startsWith('https://wa.me/584121234567?text='));
const text=decodeURIComponent(new URL(url).searchParams.get('text'));
assert.ok(text.includes('POLADENT Casa Dental'));
assert.ok(text.includes('Horno Lótus'));
assert.ok(text.includes('Marca: VRC'));
assert.ok(text.includes(link));
assert.ok(text.includes('precio y disponibilidad'));
const unavailable=whatsappInquiryURL('584121234567',{...product,status:'sold_out'},link);
assert.ok(decodeURIComponent(new URL(unavailable).searchParams.get('text')).includes('cuándo estará disponible'));
assert.equal(whatsappInquiryURL('',product,link),'');
assert.equal(whatsappInquiryURL('04121234567',product,link),'');
assert.equal(whatsappInquiryURL('hello',product,link),'');
assert.equal(whatsappInquiryURL('58412?bad',product,link),'');
const publicScript=readFileSync(new URL('./public-catalog.js',import.meta.url),'utf8');
assert.ok(publicScript.includes('block.hidden=!selected||contacts.length===0'));
assert.ok(publicScript.includes('getWhatsAppContacts().catch(() => [])'));
const adminFile=readFileSync(new URL('./admin.html',import.meta.url),'utf8');
assert.ok(adminFile.includes('href="contacto.html"'));
console.log('Consulta por WhatsApp: pruebas aprobadas.');
